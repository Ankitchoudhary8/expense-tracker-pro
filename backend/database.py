import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
DB_PATH = Path(os.environ.get("EXPENSE_DB_PATH", str(Path(__file__).resolve().parent / "expenses.db"))).expanduser()

# A mounted volume must exist before deployment; never silently fall back to ephemeral storage.
def validate_database_location():
    if os.environ.get("EXPENSE_DB_PATH"):
        parent = DB_PATH.parent
        if not parent.is_dir():
            raise RuntimeError(f"Database directory does not exist: {parent}. Mount persistent storage before starting.")
        if not os.access(parent, os.W_OK):
            raise RuntimeError(f"Database directory is not writable: {parent}")

class InsertResult:
    def __init__(self, row_id):
        self.lastrowid = row_id

class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        if sql.lstrip().upper().startswith("INSERT INTO EXPENSES"):
            cursor = self.connection.execute(sql + " RETURNING id", params)
            return InsertResult(cursor.fetchone()["id"])
        return self.connection.execute(sql, params)

    def commit(self):
        self.connection.commit()

@contextmanager
def get_connection():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row
        with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10) as raw:
            yield PostgresConnection(raw)
        return

    connection = sqlite3.connect(DB_PATH)
    connection.row_factory = sqlite3.Row
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()

def init_db():
    if DATABASE_URL:
        with get_connection() as connection:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS expenses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL,
                    amount DOUBLE PRECISION NOT NULL CHECK(amount > 0),
                    category TEXT NOT NULL,
                    date TEXT NOT NULL,
                    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)
            connection.execute("""
                CREATE TABLE IF NOT EXISTS budgets (
                    month TEXT PRIMARY KEY,
                    amount DOUBLE PRECISION NOT NULL CHECK(amount > 0)
                )
            """)
        return
    validate_database_location()
    with get_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS expenses (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL,
                amount REAL NOT NULL CHECK(amount > 0),
                category TEXT NOT NULL,
                date TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS budgets (
                month TEXT PRIMARY KEY,
                amount REAL NOT NULL CHECK(amount > 0)
            )
        """)
        connection.commit()
